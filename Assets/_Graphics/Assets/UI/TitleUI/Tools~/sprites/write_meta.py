if __name__ == '__main__':
    src = sys.argv[1]
    man = json.load(open(os.path.join(src, 'manifest.json'), encoding='utf-8'))
    for name, info in man.items():
        l, b, r, t = info['border']
        meta = TEMPLATE.format(guid=uuid.uuid4().hex, ppu=PPU, l=l, b=b, r=r, t=t,
                               wrap=info.get('wrap', 1), sprite_id=uuid.uuid4().hex)
        with open(os.path.join(src, name + '.png.meta'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(meta)
    print(len(man), 'meta files')
